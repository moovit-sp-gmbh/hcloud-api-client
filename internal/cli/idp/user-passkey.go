func init() {
	userPasskeyListCommand.Flags().String("token", "", "authorization token")
	userPasskeyOptionsCommand.Flags().String("token", "", "authorization token")
	userPasskeyVerifyCommand.Flags().String("token", "", "authorization token")
	userPasskeyVerifyCommand.Flags().String("body", "{}", "request body as JSON")
	userPasskeyDeleteCommand.Flags().String("credentialId", "", "")
	userPasskeyDeleteCommand.Flags().String("token", "", "authorization token")

	userPasskeyCommand.AddCommand(userPasskeyListCommand)
	userPasskeyCommand.AddCommand(userPasskeyOptionsCommand)
	userPasskeyCommand.AddCommand(userPasskeyVerifyCommand)
	userPasskeyCommand.AddCommand(userPasskeyDeleteCommand)
}

var userPasskeyCommand = &cobra.Command{
	Use:   "passkey",
	Short: "Commands for passkey",
	Run: func(cmd *cobra.Command, args []string) {
		cmd.Help()
	},
}

var userPasskeyListCommand = &cobra.Command{
	Use:   "list",
	Short: "List the passkeys registered for the authenticated user",
	Long:  "Required scopes: IDP_USER_READ",
	RunE: func(cmd *cobra.Command, args []string) error {
		client, err := clients.NewIDPClient(cmd)
		if err != nil {
			return err
		}

		service := internal.New()
		latest, err := service.GetLatest()
		if err != nil {
			return err
		}

		jwt, err := command.GetArg(cmd, command.StringFlagIfSet("token"), command.ContextIfValidString(latest.Jwt), command.PromptString("authorization token"))
		if err != nil {
			return err
		}
		latest.Jwt = sql.NullString{Valid: true, String: jwt}

		res, err := client.GetV1UserPasskeyWithResponse(context.TODO(), func(_ context.Context, req *http.Request) error {
			req.Header.Set("authorization", jwt)
			return nil
		})
		if err != nil {
			return err
		}

		var data any
		err = json.Unmarshal(res.Body, &data)
		if err != nil {
			return err
		}
		text, err := command.JSON(data)
		if err != nil {
			return err
		}

		if res.StatusCode() >= 200 && res.StatusCode() < 300 {
			service.Push(latest)
		}

		command.SetResult(cmd, text)

		return nil
	},
}

