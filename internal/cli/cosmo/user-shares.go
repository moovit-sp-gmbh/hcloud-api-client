package cosmo

import (
	"context"
	"database/sql"
	"encoding/json"
	"net/http"

	"github.com/moovit-sp-gmbh/hcloud-cli-repl/internal"
	"github.com/moovit-sp-gmbh/hcloud-cli-repl/internal/clients"
	"github.com/moovit-sp-gmbh/hcloud-cli-repl/internal/clients/cosmoClient"
	"github.com/moovit-sp-gmbh/hcloud-cli-repl/internal/command"
	"github.com/spf13/cobra"
)

func init() {
	userSharesSearchCommand.Flags().String("token", "", "authorization token")
	userSharesSearchCommand.Flags().Float32("limit", 0, "Page size")
	userSharesSearchCommand.Flags().Float32("page", 0, "Page index")
	userSharesSearchCommand.Flags().String("body", "{}", "request body as JSON")

	userSharesCommand.AddCommand(userSharesSearchCommand)
	userCommand.AddCommand(userSharesCommand)
}

var userCommand = &cobra.Command{
	Use:   "user",
	Short: "Commands for user",
	Run: func(cmd *cobra.Command, args []string) {
		cmd.Help()
	},
}

var userSharesCommand = &cobra.Command{
	Use:   "shares",
	Short: "Commands for shares",
	Run: func(cmd *cobra.Command, args []string) {
		cmd.Help()
	},
}

var userSharesSearchCommand = &cobra.Command{
	Use:   "search",
	Short: "Search shares that a user is linked to",
	RunE: func(cmd *cobra.Command, args []string) error {
		client, err := clients.NewCosmoClient(cmd)
		if err != nil {
			return err
		}

		service := internal.New()
		latest, err := service.GetLatest()
		if err != nil {
			return err
		}

		jwt, err := command.GetArg(cmd, command.StringFlagIfSet("token"), command.ContextIfValidString(latest.Jwt), command.PromptString("authorization token"))
		if err != nil {
			return err
		}
		latest.Jwt = sql.NullString{Valid: true, String: jwt}

		params := &cosmoClient.PostV1UserSharesSearchParams{}

		if cmd.Flags().Changed("limit") {
			limit, err := cmd.Flags().GetFloat32("limit")
			if err != nil {
				return err
			}
			params.Limit = &limit
		}

		if cmd.Flags().Changed("page") {
			page, err := cmd.Flags().GetFloat32("page")
			if err != nil {
				return err
			}
			params.Page = &page
		}

		bodyJSON, err := cmd.Flags().GetString("body")
		if err != nil {
			return err
		}
		var body cosmoClient.PostV1UserSharesSearchJSONRequestBody
		err = json.Unmarshal([]byte(bodyJSON), &body)
		if err != nil {
			return err
		}

		res, err := client.PostV1UserSharesSearchWithResponse(context.TODO(), params, body, func(_ context.Context, req *http.Request) error {
			req.Header.Set("authorization", jwt)
			return nil
		})
		if err != nil {
			return err
		}

		var data any
		err = json.Unmarshal(res.Body, &data)
		if err != nil {
			return err
		}
		text, err := command.JSON(data)
		if err != nil {
			return err
		}

		if res.StatusCode() >= 200 && res.StatusCode() < 300 {
			service.Push(latest)
		}

		command.SetResult(cmd, text)

		return nil
	},
}
